#!/usr/bin/env python3
"""Build-only FriBidi shaping/bidi for fixed translated UI; no runtime dependency.
Format slots are protected with Latin tokens before bidi, restored afterwards.
Do not feed arbitrary logical Arabic to ImGui's non-shaping text renderer.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import textwrap
MOD=Path(__file__).resolve().parents[1]
FORMAT=re.compile(r'%(?:[-+ #0]*\d*(?:\.\d+)?(?:ll|l|z)?[diuoxXfFeEgGcs]|%)')
def shape(s,wrap=False):
    slots=[]
    def hold(m):
        slots.append(m[0]);return f'FMTTOKEN{len(slots)-1}END'
    s=FORMAT.sub(hold,s)
    if wrap:s='\n'.join(textwrap.fill(line,width=48,break_long_words=False,break_on_hyphens=False) for line in s.split('\n'))
    s=subprocess.run(['fribidi','--rtl','--nopad','--nobreak','--clean'],input=s+'\n',text=True,capture_output=True,check=True).stdout.rstrip('\n')
    # Reordered varargs with differing types are unsafe even if logical format
    # signatures matched. Split multi-value translated messages into lines.
    if re.findall(r'FMTTOKEN(\d+)END',s)!=[str(i) for i in range(len(slots))]:
        raise ValueError('bidi reordered format arguments; split this message')
    for i,slot in enumerate(slots):s=s.replace(f'FMTTOKEN{i}END',slot)
    if 'FMTTOKEN' in s:raise ValueError('damaged format token')
    return s
def outputs():
    d=json.loads((MOD/'ui/ar.json').read_text())
    for name in ['Health protection','Body / collision protection','One-hit wreck (player collisions)','Infinite Nitrous','Unlimited RAM charge / 2x launch (Alt)']:
        for state in ['ON','OFF']:d[name+': '+state]=d[name]+': '+d[state]
    entries=[]
    for en,ar in d.items():
        if FORMAT.findall(en)!=FORMAT.findall(ar):raise ValueError('format signature mismatch: '+en)
        entries.append('{'+','.join(json.dumps(x,ensure_ascii=False) for x in [en,shape(ar),shape(ar,True)])+'},')
    table='// Generated by tools/embed_ui.py. Logical Arabic: ui/ar.json.\nstatic const Translation translations[]={\n'+'\n'.join(entries)+'\n};\n'
    font=(MOD/'assets/DejaVuSans.ttf').read_bytes()
    data='// Generated embedded unmodified DejaVu Sans. See assets/DejaVu-LICENSE.txt.\nstatic unsigned char uiFontData[]={\n'+''.join(','.join(str(b) for b in font[i:i+32])+',\n' for i in range(0,len(font),32))+'};\n'
    return {'src/ui_strings.h':table,'src/ui_font.h':data}
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,data in outputs().items():
        path=MOD/path
        if a.check:
            if path.read_text()!=data:raise SystemExit('Stale generated UI: '+str(path))
        else:path.write_text(data)
if __name__=='__main__':main()
